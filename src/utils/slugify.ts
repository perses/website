/**
 * slugify reproduces the algorithm of python-markdown's toc extension used by the previous mkdocs website,
 * so anchors and URLs written for it keep working.
 */
export function slugify(value: string, separator = '-'): string {
  const ascii = value
    .normalize('NFKD')
    // oxlint-disable-next-line no-control-regex
    .replace(/[^\x00-\x7F]/g, '');
  const cleaned = ascii
    .replace(/[^\w\s-]/g, '')
    .trim()
    .toLowerCase();
  const escapedSeparator = separator.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return cleaned.replace(new RegExp(`[${escapedSeparator}\\s]+`, 'g'), separator);
}

/**
 * uniqueSlug makes the slug unique among the ones already generated by appending `_1`, `_2`, ... like python-markdown.
 */
export function uniqueSlug(slug: string, used: Set<string>): string {
  let candidate = slug;
  while (candidate === '' || used.has(candidate)) {
    const match = /^(.*)_(\d+)$/.exec(candidate);
    candidate = match ? `${match[1]}_${Number(match[2]) + 1}` : `${candidate}_1`;
  }
  used.add(candidate);
  return candidate;
}
