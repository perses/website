import { dirname } from 'node:path';
import { Transform } from 'node:stream';
import { fileURLToPath } from 'node:url';
import { CacheProvider } from '@emotion/react';
import createEmotionServer from '@emotion/server/create-instance';
import { createReadableStreamFromReadable } from '@react-router/node';
import { renderToPipeableStream } from 'react-dom/server';
import { type EntryContext, ServerRouter } from 'react-router';
import { pageCacheKey, readCacheEntry, writeCacheEntry } from './content/render-cache.server';
import { createEmotionCache } from './theme/createEmotionCache';

export const streamTimeout = 10_000;

/**
 * prerenderCacheKey returns the key of a prerendered page in the render cache (see src/content/render-cache.server.ts),
 * or undefined when the request is not a prerendering of the build.
 */
function prerenderCacheKey(request: Request, status: number, routerContext: EntryContext): string | undefined {
  if (request.headers.get('X-React-Router-Prerender') !== 'yes') {
    return undefined;
  }
  const { loaderData, actionData, errors } = routerContext.staticHandlerContext;
  const { pathname, search } = new URL(request.url);
  // The server build is a single file: the directory of this module is the server build directory.
  const serverBuildDir = dirname(fileURLToPath(import.meta.url));
  return pageCacheKey(serverBuildDir, `${pathname}${search}`, status, { loaderData, actionData, errors });
}

/**
 * handleRequest renders the pages at build time (prerendering) and in the dev server. The whole document is rendered
 * before being sent, so the critical CSS generated by Emotion can be extracted and injected in the head.
 * During the build, a page whose code and data didn't change since the previous build is reused from the render cache.
 */
export default function handleRequest(
  request: Request,
  responseStatusCode: number,
  responseHeaders: Headers,
  routerContext: EntryContext,
) {
  const cacheKey = prerenderCacheKey(request, responseStatusCode, routerContext);
  const cached = cacheKey === undefined ? undefined : readCacheEntry('pages', cacheKey);
  if (cached !== undefined) {
    responseHeaders.set('Content-Type', 'text/html');
    return Promise.resolve(new Response(cached, { headers: responseHeaders, status: responseStatusCode }));
  }

  const cache = createEmotionCache();
  const { extractCriticalToChunks, constructStyleTagsFromChunks } = createEmotionServer(cache);

  return new Promise<Response>((resolve, reject) => {
    let allReady = false;
    let failed = false;
    const { pipe, abort } = renderToPipeableStream(
      <CacheProvider value={cache}>
        <ServerRouter context={routerContext} url={request.url} />
      </CacheProvider>,
      {
        onAllReady() {
          allReady = true;
          const chunks: Buffer[] = [];
          const transform = new Transform({
            transform(chunk: Buffer, _encoding, callback) {
              chunks.push(chunk);
              callback();
            },
            flush(callback) {
              const html = Buffer.concat(chunks).toString();
              const emotionChunks = extractCriticalToChunks(html);
              // A `</style>` inside a CSS value would close the style element: escape the `<`.
              emotionChunks.styles = emotionChunks.styles.map((style) => ({
                ...style,
                css: style.css.replace(/<(?=\/?style\b)/gi, '\\3c '),
              }));
              const styles = constructStyleTagsFromChunks(emotionChunks);
              const page = styles ? html.replace('</head>', () => `${styles}</head>`) : html;
              if (cacheKey !== undefined && !failed) {
                writeCacheEntry('pages', cacheKey, page);
              }
              this.push(page);
              callback();
            },
          });
          responseHeaders.set('Content-Type', 'text/html');
          resolve(
            new Response(createReadableStreamFromReadable(transform), {
              headers: responseHeaders,
              status: responseStatusCode,
            }),
          );
          pipe(transform);
        },
        onShellError(error: unknown) {
          reject(error);
        },
        onError(error: unknown) {
          responseStatusCode = 500;
          failed = true;
          if (allReady) {
            console.error(error);
          }
        },
      },
    );
    setTimeout(abort, streamTimeout + 1000);
  });
}
